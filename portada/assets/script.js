const translationElements = document.querySelectorAll('[data-i18n]');
const languageToggle = document.querySelector('#languageToggle');
const languageCodes = document.querySelectorAll('[data-lang-code]');
const descriptionMeta = document.querySelector('meta[name="description"]');
const calendarButtons = [
  document.querySelector('#calendarButton'),
  document.querySelector('#calendarButtonBottom')
].filter(Boolean);
const toast = document.querySelector('#toast');
let currentLanguage = 'pt';
let toastTimeout;

function setLanguage(language, persist = true) {
  const nextLanguage = language === 'es' ? 'es' : 'pt';
  currentLanguage = nextLanguage;
  const copy = translations[nextLanguage];

  document.documentElement.lang = nextLanguage === 'pt' ? 'pt-BR' : 'es';
  document.title = copy.title;
  descriptionMeta?.setAttribute('content', copy.description);

  translationElements.forEach((element) => {
    const value = copy[element.dataset.i18n];
    if (value) {
      element.textContent = value;
    }
  });

  languageCodes.forEach((code) => {
    code.classList.toggle('is-active', code.dataset.langCode === nextLanguage);
  });

  if (languageToggle) {
    languageToggle.setAttribute(
      'aria-label',
      nextLanguage === 'pt' ? 'Ver a página em espanhol' : 'Ver la página en portugués'
    );
  }

  if (persist) {
    try {
      localStorage.setItem('dembogurski-language', nextLanguage);
    } catch {
      // A preferência continua válida nesta visita mesmo sem armazenamento local.
    }
  }
}

function preferredLanguage() {
  const requested = new URLSearchParams(window.location.search).get('lang');
  if (requested === 'pt' || requested === 'es') {
    return requested;
  }

  try {
    const saved = localStorage.getItem('dembogurski-language');
    if (saved === 'pt' || saved === 'es') {
      return saved;
    }
  } catch {
    // Português permanece como idioma padrão.
  }
  return 'pt';
}

function showToast() {
  if (!toast) {
    return;
  }

  window.clearTimeout(toastTimeout);
  toast.hidden = false;
  toastTimeout = window.setTimeout(() => {
    toast.hidden = true;
  }, 3800);
}

function downloadCalendar() {
  const calendar = [
    'BEGIN:VCALENDAR',
    'VERSION:2.0',
    'PRODID:-//Familia Dembogurski//1 Encontro//PT-BR',
    'CALSCALE:GREGORIAN',
    'METHOD:PUBLISH',
    'BEGIN:VEVENT',
    'UID:primeiro-encontro-familia-dembogurski-2027@dembogurski.com',
    'DTSTAMP:20261024T120000Z',
    'DTSTART;VALUE=DATE:20270918',
    'DTEND;VALUE=DATE:20270919',
    'SUMMARY:1º Encontro Família Dembogurski',
    'LOCATION:Salão da Comunidade de Rocinha - Três de Maio, RS',
    'DESCRIPTION:Encontro da Família Dembogurski.',
    'END:VEVENT',
    'END:VCALENDAR'
  ].join('\r\n');

  const blob = new Blob([calendar], { type: 'text/calendar;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = 'encontro-familia-dembogurski-2027.ics';
  document.body.append(link);
  link.click();
  link.remove();
  window.setTimeout(() => URL.revokeObjectURL(url), 1000);
  showToast();
}

languageToggle?.addEventListener('click', () => {
  setLanguage(currentLanguage === 'pt' ? 'es' : 'pt');
});

calendarButtons.forEach((button) => {
  button.addEventListener('click', downloadCalendar);
});

const revealElements = document.querySelectorAll('.reveal');
if ('IntersectionObserver' in window) {
  const revealObserver = new IntersectionObserver((entries, observer) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add('is-visible');
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12 });

  revealElements.forEach((element) => revealObserver.observe(element));
} else {
  revealElements.forEach((element) => element.classList.add('is-visible'));
}

setLanguage(preferredLanguage(), false);
